port_free() {
    ! (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

find_free_port() {
    local p=$1
    local tries=0
    while ! port_free "$p" && [ "$tries" -lt 50 ]; do
        p=$((p + 1))
        tries=$((tries + 1))
    done
    echo "$p"
}

ensure_panel_password() {
    if [ -s "$APP_DIR/.panel-password" ]; then
        PANEL_PASSWORD=$(cat "$APP_DIR/.panel-password" | tr -d '[:space:]')
        save_config
        return
    fi
    if [ -z "$PANEL_PASSWORD" ]; then
        PANEL_PASSWORD=$(tr -dc A-Za-z0-9 </dev/urandom | head -c 16)
        save_config
    fi
    umask 077 && echo "$PANEL_PASSWORD" > "$APP_DIR/.panel-password"
}

write_panel_unit() {
    local UNIT_DIR="$HOME/.config/systemd/user"
    mkdir -p "$UNIT_DIR"
    cat > "$UNIT_DIR/ironman-panel.service" << EOF
[Unit]
Description=IRONMAN web panel
