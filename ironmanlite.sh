[Service]
Type=simple
WorkingDirectory=$APP_DIR
Environment=PYTHONUNBUFFERED=1
Environment=PANEL_PORT=$PANEL_PORT
ExecStart=$APP_DIR/.venv/bin/python $APP_DIR/panel.py
Restart=always
RestartSec=3

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
}

panel_url() {
    local host_ip
    host_ip=$(hostname -I 2>/dev/null | awk '{print $1}')
    echo "http://${host_ip:-IP-машины}:$PANEL_PORT"
}

change_panel_port() {
    echo ""
    echo "Текущий порт панели: $PANEL_PORT"
    read -p "Новый порт 1024-65535 (Enter — оставить): " new_port
    [ -z "$new_port" ] && { info "Оставили как было."; read -p "Press Enter..."; return; }
    if ! [[ "$new_port" =~ ^[0-9]+$ ]] || [ "$new_port" -lt 1024 ] || [ "$new_port" -gt 65535 ]; then
        error "Неверный порт (нужно число 1024-65535)"
        read -p "Press Enter..."
        return
    fi
    if [ "$new_port" != "$PANEL_PORT" ] && ! port_free "$new_port"; then
        error "Порт $new_port уже занят."
        read -p "Press Enter..."
        return
    fi
    PANEL_PORT="$new_port"
    save_config
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        write_panel_unit
        systemctl --user restart ironman-panel 2>/dev/null || true
    fi
    ok "Порт панели: $PANEL_PORT. Адрес: $(panel_url)"
    read -p "Press Enter..."
}

panel_info() {
    echo ""
    echo "  Адрес панели: $(panel_url)"
    echo "  Пароль:       $(cat "$APP_DIR/.panel-password" 2>/dev/null || echo 'не найден')"
    echo "  Служба:       $(systemctl --user is-active ironman-panel 2>/dev/null || echo 'нет')"
    echo "  Локально:     curl http://127.0.0.1:$PANEL_PORT/login"
    echo ""
    read -p "Сменить порт панели? Введите новый (Enter — нет): " p
    [ -n "$p" ] && change_panel_port <<< "$p" || true
    read -p "Press Enter..."
}


