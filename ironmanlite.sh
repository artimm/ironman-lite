install_python() {
    info "Проверяем Python и зависимости..."
    if ! python3 -c 'import venv' 2>/dev/null; then
        info "Доусанавливаем python3-venv/python3-pip (нужен sudo)..."
        sudo apt-get update -qq || true
        sudo apt-get install -y python3-venv python3-pip curl || { error "Не удалось установить python3-venv"; return 1; }
    fi
    command -v curl >/dev/null 2>&1 || sudo apt-get install -y curl || true

    info "Создаём виртуальное окружение и ставим зависимости (пару минут)..."
    if ! (cd "$APP_DIR" && python3 -m venv .venv \
          && .venv/bin/pip install --quiet --upgrade pip wheel \
          && .venv/bin/pip install --quiet -r requirements.txt); then
        error "Не удалось установить зависимости Python"
        return 1
    fi
    ok "Python-окружение готово."
}

detect_systemd() {
    if command -v systemctl >/dev/null 2>&1 \
       && [ "$(systemctl --user is-system-running 2>/dev/null)" != "offline" ] \
       && systemctl --user daemon-reload >/dev/null 2>&1; then
        HAVE_USER_SYSTEMD=1
    else
        HAVE_USER_SYSTEMD=0
        warn "systemd (user) недоступен — автозапуск не настроен, запускайте пунктом «Запустить в терминале»."
    fi
}

write_unit() {
    local UNIT_DIR="$HOME/.config/systemd/user"
    mkdir -p "$UNIT_DIR"
    cat > "$UNIT_DIR/$SERVICE.service" << EOF
[Unit]
Description=IronMan Telegram notes bot
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$APP_DIR
EnvironmentFile=$APP_DIR/.env
Environment=PYTHONUNBUFFERED=1
ExecStart=$APP_DIR/.venv/bin/python -m bot.bot
Restart=always
RestartSec=5

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
}

enable_linger() {
    sudo loginctl enable-linger "$USER" >/dev/null 2>&1 \
        && ok "Автозапуск переживёт выход из системы (linger включён)." \
        || warn "Не включён linger — служба стартует при входе в систему. Включить: sudo loginctl enable-linger $USER"
}

