change_timezone() {
    echo ""
    echo "Текущий часовой пояс бота: $TIMEZONE"
    echo "Влияет на напоминания («завтра в 15:00»). По умолчанию: Europe/Samara (UTC+4)."
    echo "Примеры: Europe/Moscow (UTC+3), Asia/Dubai (UTC+4), Asia/Yekaterinburg (UTC+5), UTC"
    read -p "Новый пояс (Enter — оставить $TIMEZONE): " new_tz
    [ -z "$new_tz" ] && { info "Оставили как было."; read -p "Press Enter..."; return; }
    if ! [[ "$new_tz" =~ ^[A-Za-z_]+/[A-Za-z_0-9+\-]+$ ]] && [ "$new_tz" != "UTC" ]; then
        error "Название должно быть в формате IANA, например Europe/Moscow"
        read -p "Press Enter..."
        return
    fi
    if ! [ -f "/usr/share/zoneinfo/$new_tz" ]; then
        error "Неизвестный пояс: $new_tz"
        read -p "Press Enter..."
        return
    fi
    TIMEZONE="$new_tz"
    save_config
    if installed; then
        write_env
        svc_restart
        sleep 2
    fi
    ok "Часовой пояс бота: $TIMEZONE, применён."
    read -p "Press Enter..."
}

