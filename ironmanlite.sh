tg_check_ip() {
    local code
    code=$(curl -s --resolve api.telegram.org:443:$1 -m 5 https://api.telegram.org/ -o /dev/null -w '%{http_code}' 2>/dev/null)
    [ "$code" = "302" ] || [ "$code" = "200" ]
}

net_diagnostics() {
    echo ""
    echo "───────────────── ДИАГНОСТИКА СЕТИ ─────────────────"
    echo "resolve api.telegram.org -> $(getent ahostsv4 api.telegram.org 2>/dev/null | head -1 | awk '{print $1}')"
    local code
    code=$(curl -s -m 6 https://api.telegram.org/ -o /dev/null -w '%{http_code}' 2>/dev/null)
    if [ "$code" = "302" ] || [ "$code" = "200" ]; then
        ok "Прямой доступ к api.telegram.org: работает (HTTP $code)"
    else
        warn "Прямой доступ к api.telegram.org: НЕ РАБОТАЕТ (код: ${code:-нет})"
    fi
    echo "Закреплено в /etc/hosts: $(grep api.telegram.org /etc/hosts 2>/dev/null | head -1 || echo '— ничего')"
    if [ -n "$PROXY_URL" ]; then
        echo "Прокси бота: $PROXY_URL"
    else
        echo "Прокси бота: не задан"
    fi
    echo ""
    echo "Проверка известных IP Telegram (TCP+TLS+HTTP):"
    local ip
    for ip in $TELEGRAM_IPS; do
        if tg_check_ip "$ip"; then echo "  $ip  — доступен"; else echo "  $ip  — блокируется"; fi
    done
    if svc_active; then
        echo ""
        echo "Служба: active"
        journalctl --user -u "$SERVICE" -n 1 --no-pager -o cat 2>/dev/null | cut -c1-110
    else
        echo ""
        echo "Служба: не запущена"
    fi
    echo "────────────────────────────────────────────────────"
    echo ""
    read -p "Press Enter..."
}

fix_telegram() {
    info "Подбираем рабочий IP для api.telegram.org..."
    local working="" ip
    for ip in $TELEGRAM_IPS; do
        printf "  %s ... " "$ip"
        if tg_check_ip "$ip"; then
            echo "доступен"
            working="$ip"
            break
        else
            echo "блокируется"
        fi
    done
    if [ -z "$working" ]; then
        error "Ни один IP Telegram не доступен. Настройте прокси (пункт 7) и повторите."
        read -p "Press Enter..."
        return
    fi
    sudo sed -i '/api\.telegram\.org/d' /etc/hosts
    echo "$working api.telegram.org  # ironman-pin" | sudo tee -a /etc/hosts >/dev/null
    svc_restart
    sleep 3
    ok "Закреплён рабочий IP: $working"
    echo ""
    read -p "Press Enter..."
}

