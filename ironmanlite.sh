set_proxy() {
    echo ""
    if [ -n "$PROXY_URL" ]; then
        echo "Текущий прокси: $PROXY_URL"
    else
        echo "Прокси не задан (бот ходит в Telegram напрямую)."
    fi
    echo "Формат: http://user:pass@host:port или socks5://user:pass@host:port"
    read -p "PROXY_URL (Enter — оставить как есть, 'нет' — убрать): " new_proxy
    if [ -z "$new_proxy" ]; then
        info "Оставили как было."
        read -p "Press Enter..."
        return
    fi
    if [ "${new_proxy,,}" = "нет" ] || [ "${new_proxy,,}" = "no" ]; then
        PROXY_URL=""
    else
        if ! [[ "$new_proxy" =~ ^(https?|socks[45]):// ]]; then
            error "Прокси должен начинаться с http:// или socks5://"
            read -p "Press Enter..."
            return
        fi
        PROXY_URL="$new_proxy"
    fi
    save_config
    if installed; then
        write_env
        svc_restart
        sleep 2
        ok "Прокси применён, бот перезапущен."
    else
        ok "Прокси сохранён. Применится при установке."
    fi
    read -p "Press Enter..."
}

