    echo "  Данные:     $(du -sh "$APP_DIR/data" 2>/dev/null | cut -f1) ($APP_DIR/data)"
    local code
    code=$(curl -s -m 6 https://api.telegram.org/ -o /dev/null -w '%{http_code}' 2>/dev/null)
    if [ "$code" = "302" ] || [ "$code" = "200" ]; then
        echo "  Telegram:   доступен"
    else
        echo "  Telegram:   НЕ доступен (пункт 4 — фикс, пункт 7 — прокси)"
    fi
    if [ -n "$BOT_TOKEN" ]; then
        echo "  Токен:      задан"
    else
        echo "  Токен:      НЕ ЗАДАН (пункт 5)"
    fi
    echo ""
    read -p "Press Enter..."
}

start_restart() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено."
        read -p "Press Enter..."
        return
    fi
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        systemctl --user restart "$SERVICE"
        sleep 2
        ok "Служба перезапущена: $(systemctl --user is-active "$SERVICE")"
    else
        warn "systemd недоступен — запустите пунктом 2 (в терминале)."
    fi
    echo ""
    read -p "Press Enter..."
}

stop_service() {
    echo ""
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        systemctl --user stop "$SERVICE"
        ok "Служба остановлена."
    else
        pkill -f "python -m bot.bot" 2>/dev/null && ok "Процесс остановлен." || warn "Процесс не найден."
    fi
    echo ""
    read -p "Press Enter..."
}

show_logs() {
    echo ""
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        journalctl --user -u "$SERVICE" -n 50 --no-pager
    else
        tail -n 50 "$APP_DIR/data/bot.log" 2>/dev/null || warn "Логов пока нет."
    fi
    echo ""
    read -p "Press Enter..."
}

run_tests() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено."
        read -p "Press Enter..."
        return
    fi
    info "Запускаем тесты (pytest)..."
    (cd "$APP_DIR" && .venv/bin/python -m pytest -q)
    echo ""
    read -p "Press Enter..."
}

backup_data() {
    echo ""
    if [ ! -d "$APP_DIR/data" ]; then
        warn "Папка data пока пуста — бэкапить нечего."
        read -p "Press Enter..."
        return
    fi
    local FNAME="ironman-lite-backup-$(date +%Y%m%d-%H%M%S).tgz"
    info "Архивируем заметки и вложения..."
    tar -czf "./$FNAME" -C "$APP_DIR" data
    ok "Бэкап сохранён: $FNAME"
    read -p "Press Enter..."
}

run_foreground() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено. Сначала установка (пункт 1)."
        read -p "Press Enter..."
        return
    fi
    warn "Бот запустится прямо в этом терминале. Останов: Ctrl+C"
    read -p "Запустить? (y/N): " ans
    [[ ! "$ans" =~ ^[Yy]$ ]] && return
    cd "$APP_DIR" && exec .venv/bin/python -m bot.bot
}

remove_app() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено."
        read -p "Press Enter..."
        return
    fi
    warn "Будут УДАЛЕНЫ файлы приложения и все заметки ($APP_DIR)!"
    read -p "Остановить службу и удалить? (y/N): " ans
    [[ ! "$ans" =~ ^[Yy]$ ]] && return
    [ "$HAVE_USER_SYSTEMD" = "1" ] && systemctl --user disable --now "$SERVICE" 2>/dev/null
    rm -f "$HOME/.config/systemd/user/$SERVICE.service"
    systemctl --user daemon-reload 2>/dev/null
    rm -rf "$APP_DIR"
    ok "Удалено."
    read -p "Press Enter..."
}

