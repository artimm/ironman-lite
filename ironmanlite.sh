    echo "Где взять: https://platform.openai.com/api-keys"
    read -p "Вставьте новый ключ (Enter — оставить как есть): " new_key
    if [ -z "$new_key" ]; then
        info "Оставили как было."
        read -p "Press Enter..."
        return
    fi
    OPENAI_API_KEY="$new_key"
    save_config
    if installed; then
        write_env
        svc_restart
        ok "Ключ сохранён, бот перезапущен."
    else
        ok "Ключ сохранён в конфиг. Он применится при установке (пункт 1)."
    fi
    read -p "Press Enter..."
}

