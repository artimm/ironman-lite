status_info() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено. Сначала установка (пункт 1)."
        read -p "Press Enter..."
        return
    fi
    echo "  Папка:      $APP_DIR"
    echo "  Режим:      $MODE"
    if [ -n "$PROXY_URL" ]; then
        echo "  Прокси:     $PROXY_URL"
    fi
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        echo "  Служба:     $(systemctl --user is-active "$SERVICE" 2>/dev/null)"
        echo "  Рестартов:  $(systemctl --user show "$SERVICE" -p NRestarts --value 2>/dev/null)"
        local botline
        botline=$(journalctl --user -u "$SERVICE" -n 200 --no-pager 2>/dev/null | grep 'Run polling' | tail -1 | cut -c1-100)
        [ -n "$botline" ] && echo "  Бот:        $botline"
    else
        if pgrep -f "python -m bot.bot" >/dev/null 2>&1; then
            echo "  Процесс:    запущен (без службы)"
        else
            echo "  Процесс:    не запущен"
        fi
    fi
    echo "  Данные:     $(du -sh "$APP_DIR/data" 2>/dev/null | cut -f1) ($APP_DIR/data)"
    local code
    code=$(curl -s -m 6 https://api.telegram.org/ -o /dev/null -w '%{http_code}' 2>/dev/null)
    if [ "$code" = "302" ] || [ "$code" = "200" ]; then
        echo "  Telegram:   доступен"
    else
        echo "  Telegram:   НЕ доступен (пункт 4 — фикс, пункт 7 — прокси)"
    fi
    if [ -n "$BOT_TOKEN" ]; then
        echo "  Токен:      задан"
    else
        echo "  Токен:      НЕ ЗАДАН (пункт 5)"
    fi
    echo ""
    read -p "Press Enter..."
}

start_restart() {
    echo ""
    if ! installed; then
        warn "Приложение не установлено."
        read -p "Press Enter..."
        return
    fi
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        systemctl --user restart "$SERVICE"
        sleep 2
        ok "Служба перезапущена: $(systemctl --user is-active "$SERVICE")"
    else
        warn "systemd недоступен — запустите пунктом 2 (в терминале)."
    fi
    echo ""
    read -p "Press Enter..."
}

stop_service() {
    echo ""
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        systemctl --user stop "$SERVICE"
        ok "Служба остановлена."
    else
        pkill -f "python -m bot.bot" 2>/dev/null && ok "Процесс остановлен." || warn "Процесс не найден."
    fi
    echo ""
    read -p "Press Enter..."
}

show_logs() {
