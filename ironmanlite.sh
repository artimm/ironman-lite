install_all() {
    echo ""
    echo "╔═══════════════════════════════════════════╗"
    echo "║  IRONMAN LITE — установка в Ubuntu        ║"
    echo "║  (без контейнера, папка ~/ironman)        ║"
    echo "╚═══════════════════════════════════════════╝"
    echo ""

    if [ -d "$APP_DIR" ] && installed; then
        warn "Приложение уже установлено в $APP_DIR. Переустановка ЗАМЕНИТ файлы (заметки сохранятся)."
        read -p "Продолжить? (y/N): " reinstall
        [[ ! "$reinstall" =~ ^[Yy]$ ]] && { info "Отменено."; read -p "Press Enter..."; return; }
    fi

    detect_systemd

    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        systemctl --user stop "$SERVICE" 2>/dev/null || true
    else
        pkill -f "python -m bot.bot" 2>/dev/null || true
    fi

    push_app_files

    if ! install_python; then
        read -p "Press Enter..."
        return 1
    fi

    write_env

    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        write_unit
        systemctl --user enable "$SERVICE" >/dev/null 2>&1
        systemctl --user restart "$SERVICE"
        enable_linger
    fi

    info "Проверяем доступ к Telegram API..."
    local code working ip
    code=$(curl -s -m 6 https://api.telegram.org/ -o /dev/null -w '%{http_code}' 2>/dev/null)
    if [ "$code" != "302" ] && [ "$code" != "200" ]; then
        warn "Прямой доступ к Telegram не работает — подбираем рабочий IP автоматически..."
        for ip in $TELEGRAM_IPS; do
            if tg_check_ip "$ip"; then working="$ip"; break; fi
        done
        if [ -n "$working" ]; then
            sudo sed -i '/api\.telegram\.org/d' /etc/hosts
            echo "$working api.telegram.org  # ironman-pin" | sudo tee -a /etc/hosts >/dev/null
            svc_restart
            ok "Закреплён рабочий IP: $working"
        else
            warn "Ни один IP не доступен — настройте прокси (пункт 7)."
        fi
    else
        ok "Прямой доступ к Telegram работает."
    fi

    echo ""
    ok "Установка завершена!"
    echo ""
    echo "  ┌───────────────────────────────────────────────┐"
    echo "  │  IronMan — Telegram-бот заметок (LITE)        │"
    echo "  │                                               │"
    echo "  │  Папка:     $APP_DIR"
    if [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        echo "  │  Служба:    systemctl --user status ironman   "
        echo "  │  Логи:      journalctl --user -u ironman -f   "
    else
        echo "  │  Запуск:    пункт 2 меню (в терминале)        "
    fi
    echo "  │  Данные:    $APP_DIR/data"
    echo "  └───────────────────────────────────────────────┘"
    echo ""
    if [ "$HAVE_USER_SYSTEMD" = "1" ] && svc_active; then
        ok "Бот запущен. Найдите его в Telegram и отправьте /start."
    elif [ "$HAVE_USER_SYSTEMD" = "1" ]; then
        warn "Служба не активна — смотрите пункт 13 (логи)."
    fi
    if [ -z "$BOT_TOKEN" ]; then
        warn "BOT_TOKEN НЕ ЗАДАН — бот не сможет работать. Пункт 5."
    fi
    echo ""
    read -p "Press Enter..."
}

