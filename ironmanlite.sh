#!/bin/bash
# =====================================================
# IRONMAN LITE v1.0
# Установка IronMan (Telegram-бот заметок) НАПРЯМУЮ в Ubuntu,
# без LXD-контейнера. Файлы: ~/ironman, служба: systemd --user.
# Клон IRONMAN-V1.sh для локального компьютера.
#
# Использование:  bash ironmanlite.sh
# =====================================================
set -uo pipefail

APP_DIR="$HOME/ironman"
SERVICE="ironman"
CONFIG_FILE="$HOME/.ironmanlite-config"

TELEGRAM_IPS="149.154.167.220 149.154.167.198 149.154.166.220 149.154.166.110 91.108.56.107 91.108.56.130 91.108.4.136 91.108.4.138"

BOT_TOKEN=""
MODE="polling"
WEBHOOK_URL=""
WEBHOOK_PATH="/webhook"
WEBHOOK_PORT="8080"
ALLOWED_IDS=""
OPENAI_API_KEY=""
LOG_LEVEL="INFO"
PROXY_URL=""
TIMEZONE="Europe/Samara"
PANEL_PORT="8099"
PANEL_PASSWORD=""

HAVE_USER_SYSTEMD=0

[ -f "$CONFIG_FILE" ] && source "$CONFIG_FILE"

# =====================================================
# УТИЛИТЫ
# =====================================================
info()  { echo -e "\033[0;34m[INFO]\033[0m $1"; }
ok()    { echo -e "\033[0;32m[OK]\033[0m $1"; }
warn()  { echo -e "\033[0;33m[!]\033[0m $1"; }
error() { echo -e "\033[0;31m[ERROR]\033[0m $1"; }

save_config() {
    cat > "$CONFIG_FILE" << EOF
BOT_TOKEN="$BOT_TOKEN"
MODE="$MODE"
WEBHOOK_URL="$WEBHOOK_URL"
WEBHOOK_PATH="$WEBHOOK_PATH"
WEBHOOK_PORT="$WEBHOOK_PORT"
ALLOWED_IDS="$ALLOWED_IDS"
OPENAI_API_KEY="$OPENAI_API_KEY"
LOG_LEVEL="$LOG_LEVEL"
PROXY_URL="$PROXY_URL"
TIMEZONE="$TIMEZONE"
PANEL_PORT="$PANEL_PORT"
PANEL_PASSWORD="$PANEL_PASSWORD"
EOF
}

installed() {
    [ -d "$APP_DIR/.venv" ] && [ -f "$APP_DIR/bot/bot.py" ]
}

svc_active() {
    [ "$HAVE_USER_SYSTEMD" = "1" ] && systemctl --user is-active --quiet "$SERVICE" 2>/dev/null
}

svc_restart() {
    [ "$HAVE_USER_SYSTEMD" = "1" ] && systemctl --user restart "$SERVICE"
}

write_env() {
    cat > "$APP_DIR/.env" << EOF
BOT_TOKEN=$BOT_TOKEN
MODE=$MODE
WEBHOOK_URL=$WEBHOOK_URL
WEBHOOK_PATH=$WEBHOOK_PATH
WEBHOOK_PORT=$WEBHOOK_PORT
ALLOWED_IDS=$ALLOWED_IDS
OPENAI_API_KEY=$OPENAI_API_KEY
LOG_LEVEL=$LOG_LEVEL
PROXY_URL=$PROXY_URL
TZ=$TIMEZONE
EOF
    chmod 600 "$APP_DIR/.env"
}

